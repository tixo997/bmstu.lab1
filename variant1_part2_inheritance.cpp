// Лабораторная работа №3, часть 2. Вариант 1.
// Базовый класс «вектор на плоскости», производный класс «вектор в трехмерном пространстве».
// Два варианта переопределения функций:
//  1) статический полиморфизм (vec2, vec3) - функции без virtual,
//     метод выбирается по типу указателя;
//  2) динамический полиморфизм (vec2V, vec3V) - функции с virtual в базовом классе,
//     метод выбирается по типу объекта.
#include <iostream>
#include <math.h> // sqrt
#include <vector>
using namespace std;

// ---------- Статический полиморфизм ----------
class vec2 // Базовый класс - "Вектор на плоскости" (начало вектора в точке 0, 0)
{
protected:
double x, y; // Координаты конца вектора (статус доступа protected)
public:
vec2(double x, double y) // Конструктор для инициализации полей
{
this->x=x; this->y=y;
}
double len() // Вычисление длины вектора
{
return sqrt(x*x+y*y);
}
void print() // Метод для печати полей и длины вектора
{
cout<<"vec2: x="<<x<<" y="<<y<<" len="<<len()<<endl; // Печатаем значения полей и длину
}
};
class vec3: public vec2 // Производный класс - "Вектор в трехмерном пространстве"
{
double z; // Новое поле - дополнительная координата
public:
vec3(double x, double y, double z): // Конструктор
  vec2(x, y) // Явный вызов конструктора базового класса
  {
  this->z=z;
  }
  double len() // Переопределенная функция вычисления длины
  {
  double l=vec2::len(); // Вызов функции базового класса (длина проекции на плоскость)
  return sqrt(l*l+z*z);
  }
  void print() // Переопределенный метод print
  {
  cout<<"vec3: x="<<x<<" y="<<y<<" z="<<z<<" len="<<len()<<endl; // Печатаем поля и длину
  }
};

// ---------- Динамический полиморфизм ----------
class vec2V // Базовый класс - "Вектор на плоскости"
{
protected:
double x, y; // Координаты конца вектора
public:
vec2V(double x, double y) // Конструктор для инициализации полей
{
this->x=x; this->y=y;
}
virtual double len() // Вычисление длины вектора (виртуальная функция)
{
return sqrt(x*x+y*y);
}
virtual void print() // Метод для печати полей и длины вектора (виртуальный)
{
cout<<"vec2: x="<<x<<" y="<<y<<" len="<<len()<<endl; // Печатаем значения полей и длину
}
};
class vec3V: public vec2V // Производный класс - "Вектор в трехмерном пространстве"
{
double z; // Новое поле - дополнительная координата
public:
vec3V(double x, double y, double z): // Конструктор
  vec2V(x, y) // Явный вызов конструктора базового класса
  {
  this->z=z;
  }
  double len() // Переопределенная виртуальная функция вычисления длины
  {
  double l=vec2V::len(); // Вызов функции базового класса
  return sqrt(l*l+z*z);
  }
  void print() // Переопределенный метод print
  {
  cout<<"vec3: x="<<x<<" y="<<y<<" z="<<z<<" len="<<len()<<endl; // Печатаем поля и длину
  }
};

int main()
{
cout<<"1. Static polymorphism (no virtual)"<<endl;
vec2 r(3, 4); // Создается объект базового класса с вызовом конструктора
vec3 bx(3, 4, 12); // Создается объект производного класса с вызовом конструктора
r.print(); // Вызов метода через объект
bx.print(); // Вызов метода через объект
vec2 *p; // Указатель типа базового класса
p=&r; // Настраиваем на объект базового класса
p->print(); // Вызов метода через указатель
p=&bx; // Настраиваем указатель на объект производного класса
       // (преобразование типа допустимо)
p->print(); // Вызывается метод класса vec2: выбор по типу указателя
cout<<"p->len()="<<p->len()<<" (2D length, not 3D)"<<endl<<endl; // Тоже функция базового класса

cout<<"2. Dynamic polymorphism (virtual)"<<endl;
vec2V rv(3, 4); // Объект базового класса
vec3V bv(3, 4, 12); // Объект производного класса
vec2V *pv; // Указатель типа базового класса
pv=&rv; // Настраиваем на объект базового класса
pv->print(); // Вызывается метод класса vec2V
pv=&bv; // Настраиваем на объект производного класса
pv->print(); // Вызывается метод класса vec3V: выбор по типу объекта
cout<<"pv->len()="<<pv->len()<<" (3D length)"<<endl<<endl; // Вызывается функция vec3V

cout<<"3. Vector of pointers to objects of base and derived classes"<<endl;
vec2V r1(3, 4), r2(6, 8); // Объекты базового класса
vec3V b1(3, 4, 12), b2(2, 3, 6); // Объекты производного класса
vector<vec2V*> v; // Вектор указателей на объекты базового класса
v.push_back(&r1); // В одном векторе указатели
v.push_back(&b1); // на объекты базового
v.push_back(&r2); // и производного
v.push_back(&b2); // классов
double sum=0; // Сумма длин векторов
for (int i = 0; i < v.size(); i++) // Перебираем все указатели вектора
{
v[i]->print(); // Печатаем данные объекта (динамический полиморфизм)
sum+=v[i]->len(); // Длина вектора (для каждого объекта вызывается своя функция)
}
cout<<"Sum of lengths = "<<sum<<endl; // Вывод суммы
return 0;
}
